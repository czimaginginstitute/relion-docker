from __future__ import annotations

import argparse
import json
import os
import shlex
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from .binaries import ENV_BINS

MARKER = "# generated by relion-zarr-sta-client"
# Inside a container (e.g. pipeliner's `mpirun -n N /abs/wrapper/relion_refine_mpi`, or topaz exe
# paths passed to RELION) the wrapper runs the real binary directly instead of nesting apptainer.
SHIM_TEMPLATE = """#!/bin/bash
{marker}
if [ -n "${{APPTAINER_CONTAINER:-${{SINGULARITY_CONTAINER:-}}}}" ]; then exec {invocation} "$@"; fi
exec {runtime} exec --nv {env}{binds}{sif} {invocation} "$@"
"""
# keep host site-packages / PYTHONPATH out of the container
BASE_ENV = "--env PYTHONNOUSERSITE=1 --env PYTHONPATH= "
# pinned so a host MAMBA_ROOT_PREFIX can't override it
MAMBA_ROOT_PREFIX = "/home/relion/.local/share/mamba"

_UMASK = os.umask(0)
os.umask(_UMASK)


def find_runtime() -> str:
    for rt in ("apptainer", "singularity"):
        if shutil.which(rt):
            return rt
    raise SystemExit("error: neither apptainer nor singularity is on PATH (load its module and re-run)")


def _is_ours(path: Path) -> bool:
    """regular file (not a symlink) carrying our marker near the top"""
    if path.is_symlink() or not path.is_file():
        return False
    try:
        with open(path, "rb") as f:
            return MARKER.encode() in f.read(256)
    except OSError:
        return False


def _write(outdir: Path, name: str, text: str) -> None:
    # temp + rename: never writes through a symlink
    fd, tmp = tempfile.mkstemp(dir=outdir, prefix=f".{name}.")
    try:
        with os.fdopen(fd, "w") as f:
            f.write(text)
            f.flush()
            os.fsync(f.fileno())
        os.chmod(tmp, 0o777 & ~_UMASK)  # mkstemp creates 0600; apply the user's umask
        os.replace(tmp, outdir / name)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def list_system_bins(runtime: str, sif: Path) -> dict[str, str]:
    """{name: absolute path in the image} for mpirun + every relion_* in /usr/local/bin."""
    script = "cd /usr/local/bin && for b in mpirun relion_*; do command -v \"$b\"; done"
    try:
        out = subprocess.run(
            [runtime, "exec", "--env", "PATH=/usr/local/bin:/usr/bin:/bin", str(sif), "sh", "-c", script],
            capture_output=True, text=True, check=True, timeout=300,
        ).stdout.split()
    except (OSError, subprocess.SubprocessError) as e:
        raise SystemExit(f"error: couldn't list binaries in {sif} with {runtime}: {e}")
    bins = {Path(p).name: p for p in out if p.startswith("/")}
    if "mpirun" not in bins or not any(n.startswith("relion_") for n in bins):
        raise SystemExit(f"error: no mpirun/relion_* binaries found in {sif}; is it a relion-zarr-sta SIF?")
    return bins


def generate_shims(sif: Path, outdir: Path, binds: list[str], env_name: str, force: bool) -> int:
    runtime = find_runtime()
    bins = list_system_bins(runtime, sif)
    if outdir.exists() and not outdir.is_dir():
        raise SystemExit(f"error: --out {outdir} exists and is not a directory")
    outdir.mkdir(parents=True, exist_ok=True)
    wanted = set(bins) | set(ENV_BINS)
    dirs = sorted(n for n in wanted if (outdir / n).is_dir() and not (outdir / n).is_symlink())
    if dirs:
        raise SystemExit(f"error: {outdir} has directories named like wrappers ({', '.join(dirs)}); remove them")
    clash = sorted(n for n in wanted if os.path.lexists(outdir / n) and not _is_ours(outdir / n))
    if clash and not force:
        raise SystemExit(
            f"error: {outdir} already has files not generated by this tool: {', '.join(clash[:8])}"
            f"{' …' if len(clash) > 8 else ''}\nuse a dedicated --out directory, or --force to replace them"
        )
    for old in outdir.iterdir():  # stale wrappers from earlier runs
        if old.name not in wanted and _is_ours(old):
            old.unlink()

    env_cmd = ["/usr/local/bin/micromamba", "run", "-n", env_name]
    invocations = {n: [p] for n, p in bins.items()} | {n: env_cmd + [n] for n in ENV_BINS}
    all_binds = "".join(f"--bind {shlex.quote(f'{b}:{b}')} " for b in binds)
    all_binds += f"--bind {shlex.quote(f'{outdir}:{outdir}:ro')} "  # so wrapper paths resolve inside
    for name, inv in invocations.items():
        env = BASE_ENV + (f"--env MAMBA_ROOT_PREFIX={MAMBA_ROOT_PREFIX} " if name in ENV_BINS else "")
        _write(outdir, name, SHIM_TEMPLATE.format(
            marker=MARKER, runtime=runtime, env=env, binds=all_binds,
            sif=shlex.quote(str(sif)), invocation=shlex.join(inv),
        ))
    return len(invocations)


def wire_py2rely(outdir: Path) -> None:
    if shutil.which("py2rely") is None:
        print(
            "error: --wire-py2rely requires the `py2rely` CLI to be on PATH "
            "(it's a dependency of this package -- check your install)",
            file=sys.stderr,
        )
        raise SystemExit(1)

    path_line = f'export PATH={shlex.quote(str(outdir))}:"$PATH"'
    config = {"python_load": path_line, "relion_load": path_line}

    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as f:
        json.dump(config, f)
        tmp_path = f.name

    try:
        subprocess.run(["py2rely", "config", "import", tmp_path], check=True)
    finally:
        Path(tmp_path).unlink(missing_ok=True)

def main() -> None:
    parser = argparse.ArgumentParser(
        prog="relion-zarr-sta-client",
        description=(
            "Native client for relion-zarr-sta. Installs py2rely and zarr-particle-tools "
            "(py2rely and zarr-particle-pipeline run natively -- sbatch needs the host's SLURM "
            "setup) and generates PATH shims that route RELION and zarr-particle-tools job "
            "binaries through `apptainer exec` into the container, so job scripts written for "
            "a native install work unmodified."
        ),
    )
    parser.add_argument("--sif", required=True, help="path to the .sif image")
    parser.add_argument(
        "--out", required=True, help="output directory for shim scripts (add this to PATH)"
    )
    parser.add_argument(
        "--bind",
        action="append",
        default=[],
        help="host path to bind into the container at the same path (repeatable); "
        "e.g. the shared storage your data lives under",
    )
    parser.add_argument(
        "--env-name",
        default="relion-zarr-sta",
        help="micromamba env name inside the image for env-only CLIs (default: %(default)s)",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="replace existing files in --out that weren't generated by this tool",
    )
    parser.add_argument(
        "--wire-py2rely",
        action="store_true",
        help="also point py2rely's python_load/relion_load at the generated shim "
        "directory via `py2rely config import`",
    )
    args = parser.parse_args()

    sif = Path(args.sif).expanduser().resolve()
    if not sif.is_file():
        parser.error(f"--sif {args.sif}: no such file")
    # not symlink-resolved: job scripts use the path as typed
    binds = [os.path.abspath(os.path.expanduser(b)) for b in args.bind]
    missing = [b for b in binds if not Path(b).exists()]
    if missing:
        parser.error(f"--bind path(s) not found: {', '.join(missing)}")
    bad = [b for b in binds if "," in b or ":" in b]
    if bad:
        parser.error(f"--bind paths can't contain ',' or ':': {', '.join(bad)}")

    outdir = Path(args.out).expanduser().resolve()
    count = generate_shims(sif, outdir, binds, args.env_name, args.force)
    print(f"Generated {count} shims in {outdir}")

    if args.wire_py2rely:
        wire_py2rely(outdir)
        print("Wired py2rely's python_load/relion_load to the shim directory")
    else:
        print(f"Add to PATH (or set py2rely's python_load/relion_load to): export PATH={shlex.quote(str(outdir))}:\"$PATH\"")

if __name__ == "__main__":
    main()
